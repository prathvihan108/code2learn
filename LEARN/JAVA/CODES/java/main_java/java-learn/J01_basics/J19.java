//Break statement :
//The break statement is used to exit the loop irrespective of whether the condition is true or false.

public class J19 {  
public static void main(String[] args) {  
    //using for loop  
    for(int i=10;i>0;i--){  
        if(i==7){  
            break;   //break the loop
        }  
        System.out.println(i);  
    }  
}  
}  
